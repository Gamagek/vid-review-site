test('sidebar artwork assets have unique verified WebP bytes and complete bounded provenance', () => {
  const prompts = JSON.parse(readFileSync(new URL('../docs/review-illustration-prompts.json', import.meta.url)));
  const paths = new Set();
  const hashes = new Set();
  for (const item of illustrations) {
    assert.match(item.path, /^\/review-illustrations\/[a-z0-9-]+-v\d+\.webp$/);
    assert.ok(!paths.has(item.path)); paths.add(item.path);
    const bytes = readFileSync(new URL('../public' + item.path, import.meta.url));
    assert.equal(bytes.toString('ascii', 0, 4), 'RIFF');
    assert.equal(bytes.toString('ascii', 8, 12), 'WEBP');
    assert.equal(bytes.length, item.bytes);
    assert.equal(createHash('sha256').update(bytes).digest('hex'), item.sha256);
    assert.ok(!hashes.has(item.sha256), 'each active artwork has distinct image bytes');
    hashes.add(item.sha256);
    assert.ok(bytes.length < 300_000, 'sidebar assets stay bounded');
    assert.ok(item.width >= 1200 && item.height >= 675);
    assert.match(item.alt, /[Cc]onceptual.*not video footage/);
    assert.doesNotMatch(item.alt + item.caption, /AI[\s-]*generated|generated by AI/i);
    assert.match(item.caption, /not a frame/);
    const prompt = prompts.images.find(row => row.id === item.id);
    assert.equal(prompt.sha256, item.sha256);
    assert.ok(prompt.prompt.length > 100);
    assert.match(prompt.generationMode || prompts.generationMode, /built-in image_gen\.imagegen/);
    if (item.sourceImage?.path) {
      const source = item.sourceImage;
      const original = readFileSync(new URL('../public' + source.path, import.meta.url));
      assert.equal(original.readUInt16BE(0), 0xffd8, 'Source copies retain JPEG bytes');
      assert.equal(original.length, source.bytes);
      assert.equal(createHash('sha256').update(original).digest('hex'), source.sha256);
      assert.ok(source.path.endsWith('-' + source.sha256.slice(0,16) + '.jpg'));
      assert.equal(source.mime, 'image/jpeg');
      assert.equal(prompt.sourcePreviewCopy.url, source.url);
      assert.equal(prompt.sourcePreviewCopy.sha256, source.sha256);
      assert.equal(prompt.sourcePreviewCopy.modified, false);
    }
    if (item.previousPath) {
      const previous = prompt.history?.find(row => row.asset === 'public' + item.previousPath);
      assert.match(previous?.sha256 || '', /^[a-f0-9]{64}$/);
      assert.ok(previous.prompt.length > 100, 'retain the original generation prompt');
      assert.equal(prompt.referenceAsset.sha256, previous.sha256);
    }
  }
});

test('first-party publisher copies follow exact source identity and yield to later owner posters', () => {
  const paired = illustrations.filter(item => item.sourceImage?.path);
  assert.equal(paired.length, 20);
  for (const item of paired) {
    const row = {id:item.id,slug:item.slug,title:item.expectedTitle,source_url:item.sourceUrl,published:1};
    const before = structuredClone(row);
    assert.deepEqual(reviewSourcePreview(row,item.sourceImage.url,'https://vid.best'), {
      url:'https://vid.best'+item.sourceImage.path,width:item.sourceImage.width,height:item.sourceImage.height,
    });
    const owner = 'https://vid.best/media/uploads/new-owner-poster.webp';
    assert.equal(reviewSourcePreview(row,owner,'https://vid.best').url,owner);
    for (const change of [{title:'Changed owner title'},{slug:'changed-slug'},
      {source_url:'https://youtu.be/otherVideo1'},{published:0}]) {
      assert.equal(reviewSourcePreview({...row,...change},item.sourceImage.url,'https://vid.best'),null);
    }
    assert.equal(reviewSourcePreview(row,'data:image/jpeg;base64,unsafe','https://vid.best'),null);
    assert.deepEqual(row,before);
  }
});

test('old artwork URLs redirect to their clean versions without a database read or arbitrary redirects', async () => {
  const revised = illustrations.filter(item => item.previousPath);
  assert.ok(revised.length > 0);
  for (const item of revised) {
    assert.equal(reviewIllustrationRedirect(item.previousPath), item.path);
    assert.equal(reviewIllustrationRedirect(item.path), null);
    assert.equal(reviewIllustrationRedirect('https://example.org' + item.previousPath), null);
    for (const method of ['GET', 'HEAD']) {
      const response = await worker.fetch(new Request('https://vid.best' + item.previousPath, {method}), {});
      assert.equal(response.status, 301);
      assert.equal(response.headers.get('Location'), 'https://vid.best' + item.path);
      assert.equal(await response.text(), '');
    }
  }
  assert.equal(reviewIllustrationRedirect('/review-covers/owner.webp'), null);
});

test('owner title, source, slug and publication changes disable stale illustration matches', () => {
  for (const item of illustrations) {
    const row = {id:item.id,slug:item.slug,title:item.expectedTitle,source_url:item.sourceUrl,published:1};
    assert.equal(reviewIllustration(row)?.path, item.path);
    for (const change of [{slug:'owner-new-slug'},{title:'Owner changed title'},{source_url:'https://example.org/another-video'},{published:0},{published:false}]) {
      assert.equal(reviewIllustration({...row,...change}), null);
    }
    const trackedSource = new URL(row.source_url);
    trackedSource.searchParams.set('si', 'public-tracking');
    assert.equal(reviewIllustration({...row,source_url:trackedSource.href})?.path,item.path);
    if (trackedSource.searchParams.has('v')) {
      trackedSource.searchParams.set('v', 'different-video');
      assert.equal(reviewIllustration({...row,source_url:trackedSource.href}),null);
    }
  }
  assert.equal(reviewIllustration({id:99999}),null);
  const fb=illustrations.find(row=>row.id===149);
  assert.equal(reviewIllustration({id:fb.id,slug:fb.slug,title:fb.expectedTitle,source_url:'https://www.facebook.com/watch/?v=not-the-same-video'}),null);
});

